"""
Comprehensive MinIO MVP-Flow Test Suite
Generated by the webapp-testing skill — Phase 35 plan 04 (SC-6).

Exercises edge cases across the THREE forms of the MVP flow (MinIO input server,
MinIO output server, data source wired in+out) that the Vitest unit tests and the
Playwright E2E spec do NOT cover:

  G4  Console-port guard      — the S3 server form rejects the MinIO console port
                                (30901) with a message naming the S3 API port
                                (30900), and accepts 30900 with no port error.
  S   Masked-secret round-trip — Secret Key renders type=password; a created S3
                                server's secret is never echoed back by the API
                                (write-only) and a sentinel-edit keeps it.
  G5  Output s3Config persists — a created datasource's output S3 destination keeps
                                its bucket on API re-fetch (and on modal reopen),
                                i.e. the bucket is not dropped to null.
  G2  "file path missing" gone — when filePath (Bucket/Prefix) is set, the
                                completeness / form never shows "file path missing".
  G3  Connection survives edit — editing a datasource's schema does not blank the
                                stored inputServerId / connection config.

AUTHORITATIVE PROOF (a fresh converted JSON object in the MinIO output bucket) is
the integration test + the 35-03 live checkpoint — this script verifies the UI/API
form behavior, NEVER a Kafka topic (Phase-35 locked decision: pipeline runs over
RabbitMQ).

Reconnaissance-first: modal selectors are dumped before asserting (mirror recon.py
and s3_server_comprehensive_test.py). Every live-dependent check SKIPS cleanly when
the frontend / backends / MinIO are unreachable, so the suite is green pre-live.

Credentials: file-simulator MinIO fixtures (appuser / Appsecret123 for the
ez-phase34 buckets) — overridable via env; NO production secret in this file.

Run from src/Frontend/:
    python tests/webapp-testing/minio_mvp_flow_comprehensive_test.py

Exits 0 when all reachable checks pass (live groups skip cleanly when the app/MinIO
are unreachable); exits 1 on any reported failure.
"""
