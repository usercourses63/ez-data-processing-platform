def ant_select(page, input_id, option_text=None, option_index=0):
    """Open Ant Design Select and pick an option."""
    page.locator('.ant-select').filter(has=page.locator(f'input#{input_id}')).click()
    page.wait_for_selector('.ant-select-dropdown:not(.ant-select-dropdown-hidden)')
    page.wait_for_timeout(200)
    opts = page.locator('.ant-select-dropdown:not(.ant-select-dropdown-hidden) .ant-select-item-option:visible')
    if option_text:
        opts.filter(has_text=option_text).first.click()
    else:
        opts.nth(option_index).click()
    page.wait_for_timeout(300)


def get_sidebar_card(page):
    """Locate the completeness sidebar Card containing the progress ring."""
    return page.locator('.ant-card').filter(has=page.locator('.ant-progress-circle'))


def navigate_to_new_form(page):
    """Navigate to new datasource form and wait for load."""
    page.goto(f'{BASE_URL}/datasources/new')
    page.wait_for_load_state('networkidle')
    page.wait_for_timeout(1500)


def navigate_to_list(page):
    """Navigate to datasource list and wait for table rows."""
    page.goto(f'{BASE_URL}/datasources')
    page.wait_for_load_state('networkidle')
    page.wait_for_selector('.ant-table-tbody tr', timeout=15000)
    page.wait_for_timeout(1000)


