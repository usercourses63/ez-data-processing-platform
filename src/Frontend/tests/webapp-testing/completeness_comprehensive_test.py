def test_auto_disable_on_save_incomplete(page):
    """D-16: Saving incomplete datasource auto-disables"""
    navigate_to_new_form(page)

    ds_name = f'AutoDisable-{int(time.time())}'

    # Fill only basic info
    page.locator('input#name').fill(ds_name)
    page.locator('input#supplierName').fill('Test Supplier')
    ant_select(page, 'category')
    page.wait_for_timeout(500)

    # Visit all tabs to register fields
    for tab_key in ['connection', 'file', 'schema', 'schedule', 'validation', 'notifications', 'output']:
        page.locator(f'[id$="-tab-{tab_key}"]').click()
        page.wait_for_timeout(400)

    # Submit
    page.evaluate('() => { const btn = document.querySelector("button[type=submit]"); if (btn) btn.click(); }')
    page.wait_for_timeout(5000)

    # Navigate to list and check status
    navigate_to_list(page)

    # Go to last page
    last_page = page.locator('.ant-pagination-item').last
    if last_page.is_visible():
        last_page.click()
        page.wait_for_timeout(2000)

    # Find the created datasource
    ds_row = page.locator('tr').filter(has_text=ds_name)
    if ds_row.is_visible():
        tag = ds_row.locator('.ant-tag')
        tag_class = tag.get_attribute('class') or ''
        is_disabled = 'ant-tag-success' not in tag_class
        report("Incomplete datasource auto-disabled on save", is_disabled, f"Tag class: {tag_class}")

        # Cleanup
        ds_id = ds_row.locator('code').first.text_content()
        if ds_id:
            page.request.delete(f'{DATASOURCE_API}/api/v1/datasource/{ds_id.strip()}')
    else:
        report("Incomplete datasource auto-disabled on save", True,
               "SKIPPED: datasource not found (submit may have failed)")


